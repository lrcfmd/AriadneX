"""Child-process worker for checkpoint-backed PXRD embeddings.

The parent orchestration process serialises patterns to a temporary NPZ file
and invokes this module through ``EncoderRunner``.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Sequence

import numpy as np

from .artifact import PxrdPattern
from .embedding import CheckpointEmbedder


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Extract CLS embeddings from serialized PXRD patterns"
    )
    parser.add_argument(
        "--input", required=True, type=Path, help="input NPZ generated by PxrdEmbeddingAdapter"
    )
    parser.add_argument(
        "--output", required=True, type=Path, help="output NPZ for embeddings and theta"
    )
    parser.add_argument("--checkpoint", required=True, type=Path)
    parser.add_argument("--batch-size", type=int, default=32)
    parser.add_argument("--device", default="cpu")
    return parser


def _load_patterns(path: Path) -> tuple[list[PxrdPattern], np.ndarray]:
    if not path.is_file():
        raise FileNotFoundError(f"Embedding input does not exist: {path}")
    with np.load(path, allow_pickle=False) as payload:
        required = {"source_ids", "offsets", "x_values", "y_values", "theta"}
        missing = sorted(required - set(payload.files))
        if missing:
            raise ValueError(f"Embedding input is missing fields: {missing}")
        source_ids = [
            str(value) for value in np.asarray(payload["source_ids"]).reshape(-1).tolist()
        ]
        offsets = np.asarray(payload["offsets"], dtype=np.int64).reshape(-1)
        x_values = np.asarray(payload["x_values"], dtype=np.float32).reshape(-1)
        y_values = np.asarray(payload["y_values"], dtype=np.float32).reshape(-1)
        theta = np.asarray(payload["theta"], dtype=np.float32).reshape(-1)
    if len(offsets) != len(source_ids) + 1:
        raise ValueError("Embedding input offsets length does not match source IDs")
    if not source_ids:
        raise ValueError("Embedding input contains no source IDs")
    if offsets.size == 0 or int(offsets[0]) != 0 or np.any(np.diff(offsets) < 2):
        raise ValueError("Embedding input offsets must delimit at least two points per pattern")
    if int(offsets[-1]) != x_values.size or x_values.size != y_values.size:
        raise ValueError("Embedding input flattened arrays do not match offsets")
    if theta.size < 2 or not np.all(np.isfinite(theta)):
        raise ValueError("Embedding input theta is invalid")
    patterns = [
        PxrdPattern(
            source_id=source_id,
            x=x_values[int(start) : int(stop)],
            y=y_values[int(start) : int(stop)],
        )
        for source_id, start, stop in zip(source_ids, offsets[:-1], offsets[1:])
    ]
    return patterns, theta


def run(args: argparse.Namespace) -> None:
    patterns, theta = _load_patterns(args.input)
    embedder = CheckpointEmbedder(args.checkpoint)
    result = embedder.embed(
        patterns,
        theta=theta,
        batch_size=int(args.batch_size),
        device=str(args.device),
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(
        args.output,
        embeddings=np.asarray(result.embeddings, dtype=np.float32),
        theta=np.asarray(result.theta, dtype=np.float32),
        source_ids=np.asarray([pattern.source_id for pattern in patterns], dtype=str),
    )


def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    run(args)
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())


__all__ = ["main", "run"]
